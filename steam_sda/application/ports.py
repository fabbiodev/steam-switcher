"""Structural contracts implemented by infrastructure and test doubles."""
from typing import Any, Protocol


class StorePort(Protocol):
    def read(self, name: str, encrypted: bool = False) -> dict: ...
    def write(self, name: str, value: dict, encrypted: bool = False) -> None: ...
    def remove_journal(self) -> None: ...


class AccountRepository(Protocol):
    def all(self) -> dict: ...
    def get(self, sid: str) -> dict: ...
    def save(self, record: dict) -> None: ...
    def import_record(self, record: dict) -> dict: ...
    def delete(self, sid: str) -> None: ...
    def excluded(self) -> set[str]: ...


class AuthenticationGateway(Protocol):
    def authenticate(self, request: dict) -> dict: ...


class DeviceGateway(Protocol):
    def call(self, mode: str, profile: dict | None = None) -> dict: ...
    def is_applied(self, pid: int, launched: float) -> bool: ...


class AccountArchivesPort(Protocol):
    def read(self, path, password: str = '', known=()) -> dict: ...
    def write(self, path, record: dict, password: str = '', include_secrets: bool = True) -> None: ...


class SteamPort(Protocol):
    root: Any
    login_file: Any
    codec: Any
    def account_list(self) -> list[dict]: ...
    def read_logins(self) -> bytes: ...
    def write_logins(self, raw: bytes) -> None: ...
    def active_id(self) -> str | None: ...
    def processes(self) -> list: ...
    def games_running(self) -> bool: ...
    def stop(self) -> None: ...
    def launch(self) -> None: ...
    def exclusive(self) -> Any: ...
    def registry_value(self) -> dict: ...
    def set_registry(self, value: dict) -> None: ...
    def remember_value(self) -> dict: ...
    def set_remember(self, value: dict) -> None: ...
    def chooser_value(self) -> str | None: ...
    def set_chooser(self, value: str | None) -> None: ...
