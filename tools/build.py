"""Build from the current Python environment, without machine-specific paths."""
from pathlib import Path
import subprocess
import sys
import os
import shutil
import json
from collect_licenses import collect

root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root))
build = root / 'build'
build.mkdir(exist_ok=True)
helper = build / 'integrations/steamkit'
device = build / 'integrations/device'
helper.mkdir(parents=True, exist_ok=True)
device.mkdir(parents=True, exist_ok=True)
env = {**os.environ, 'DOTNET_CLI_TELEMETRY_OPTOUT': '1'}
cmake = shutil.which('cmake')
if cmake is None:
    candidates = list(Path(os.environ.get('ProgramFiles', 'C:/Program Files')).glob('Microsoft Visual Studio/*/*/Common7/IDE/CommonExtensions/Microsoft/CMake/CMake/bin/cmake.exe'))
    cmake = str(sorted(candidates)[-1]) if candidates else 'cmake'
subprocess.run([cmake, '-S', str(root / 'integrations/device'), '-B', str(build / 'device'), '-A', 'x64'], check=True)
subprocess.run([cmake, '--build', str(build / 'device'), '--config', 'Release', '--parallel'], check=True)
subprocess.run(['dotnet', 'publish', str(root / 'integrations/steamkit/SteamSDA.Auth.csproj'),
                '-c', 'Release', '-r', 'win-x64', '--self-contained', 'true',
                '-o', str(helper), '--nologo'], cwd=root, env=env, check=True)
subprocess.run([str(helper / 'SteamSDA.Auth.exe'), '--self-test'], check=True)
shutil.copyfile(build / 'device/Release/SteamSDADevice.dll', device / 'SteamSDADevice.dll')
shutil.copyfile(build / 'device/Release/SteamSDA.DeviceFixture.exe', helper / 'SteamSDA.DeviceFixture.exe')
fixture = {'steam_path': 'C:/SyntheticSteam', 'hwid': {
    'version': 1, 'machine_guid': 'lab-guid', 'network_id': bytes(range(16)).hex(),
    'disk_serial': 'LABDISK', 'pc_name': 'LAB-PC', 'fqdn': 'LAB-PC.lab.invalid'}}
check = subprocess.run([str(helper / 'SteamSDA.Auth.exe'), '--device-self-test'],
                       input=json.dumps(fixture), text=True, capture_output=True, timeout=60, check=True,
                       creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0))
device_test = json.loads(check.stdout)
if device_test.get('ok') is not True or device_test.get('suspended_process_test') is not True:
    raise RuntimeError('The native device bootstrap self-test failed')
print('Native device bootstrap and SteamKit machine_id self-test passed', flush=True)
licenses = collect(root)
spec = build / 'SteamSDA.spec'
spec.write_text('''# Generated by tools/build.py
from pathlib import Path
a = Analysis([%r], pathex=[%r], datas=[], runtime_hooks=[%r],
             module_collection_mode={'steam_sda': 'pyc'},
             excludes=['tkinter', 'numpy', 'cv2', 'patchright'])
# Qt 6.11 uses the unversioned Windows ICU API. A separate ICU on PATH can
# expose version-suffixed symbols and break imports. Use the OS ICU DLL.
a.binaries = [b for b in a.binaries
              if Path(b[0]).name.lower() not in {'icuuc.dll', 'icudt78.dll'}]
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name='SteamSDA',
          console=False, upx=False, contents_directory='runtime', icon=%r)
coll = COLLECT(exe, a.binaries, a.datas, name='SteamSDA', upx=False)
''' % (str(root / 'main.py'), str(root), str(root / 'tools/runtime_hook.py'), str(root / 'assets/app.ico')), encoding='utf-8')
subprocess.run([sys.executable, '-m', 'PyInstaller', '--noconfirm',
                '--distpath', str(root / 'dist'), '--workpath', str(build / 'work'),
                str(spec)], cwd=root, check=True)
distribution = root / 'dist/SteamSDA'
application = distribution / 'app'
application.mkdir(exist_ok=True)
shutil.move(str(distribution / 'runtime/steam_sda'), str(application / 'steam_sda'))
shutil.copytree(root / 'assets', distribution / 'assets')
shutil.copytree(licenses, distribution / 'licenses')
shutil.copytree(root / 'docs', distribution / 'docs')
for relative, source in (('integrations/steamkit/SteamSDA.Auth.exe', helper / 'SteamSDA.Auth.exe'),
                         ('integrations/device/SteamSDADevice.dll', device / 'SteamSDADevice.dll')):
    destination = distribution / relative
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, destination)
manifest = {'version': __import__('steam_sda').__version__, 'entrypoint': 'SteamSDA.exe',
            'app': 'app/steam_sda', 'runtime': 'runtime', 'assets': 'assets',
            'steamkit': 'integrations/steamkit/SteamSDA.Auth.exe',
            'device': 'integrations/device/SteamSDADevice.dll'}
(distribution / 'layout.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
print('Distribution organized: app/, runtime/, assets/, integrations/, docs/, licenses/', flush=True)
